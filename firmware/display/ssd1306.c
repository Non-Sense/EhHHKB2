void ssd1306_draw_char(const uint8_t x, const uint8_t y, const char ch,
                       const bool on) {
    const unsigned char uch = (unsigned char)ch;
    if (uch < FONT_FIRST_CHAR || uch > FONT_LAST_CHAR) {
        return;
    }

    const uint8_t char_index = uch - FONT_FIRST_CHAR;
    const uint8_t* char_data = font_data[char_index];

    for (uint8_t col = 0; col < FONT_WIDTH; col++) {
        const uint8_t pixel_data = char_data[col];
        for (uint8_t bit = 0; bit < 8; bit++) {
            if (x + col >= SSD1306_WIDTH) {
                return;
            }
            bool pixel_on = (pixel_data & (1 << bit)) != 0;
            ssd1306_set_pixel(x + col, y + bit, on && pixel_on);
        }
    }
}

void ssd1306_draw_string(uint8_t x, const uint8_t y, const char* str,
                         const bool on) {
    while (*str) {
        ssd1306_draw_char(x, y, *str, on);
        x += FONT_WIDTH;
        str++;
    }
}
